"""三张典型时序图：本地逐轮 / 远端闭环 / 探索式。共用同一套泳道与箭头语法，便于横向对照。"""
from d_slides1 import slide

LANES = [('<div class="p1">开发者</div>'), ('<div class="p2">AI Agent</div>'),
         ('<div class="p3">资料与文档</div>'), ('<div class="p4">运行环境</div>')]


def _seq(rows):
    out = ''
    for no, name, note, ars in rows:
        parts = []
        for a, b, cls, lb in ars:
            lo, hi = (a, b) if a < b else (b, a)
            c = cls + (' back' if a > b else '')
            parts.append('<div class="ar %s" style="--a:%d;--b:%d"><div class="bar"></div>'
                         '<div class="lb">%s</div></div>' % (c, lo, hi + 1, lb))
        _ar = ''.join(parts)
        out += ('<div class="seq-ph"><div class="seq-no"><b>%s</b><span>%s</span>'
                '<div class="seq-note">%s</div></div><div class="seq-arrows">%s</div></div>'
                % (no, name, note, _ar))
    return out


def seq_slide(title, sub, rows, note, left_chip):
    body = ('<div class="seq"><div class="seq-h"><div style="background:none;box-shadow:none"></div>%s</div>'
            '<div class="seq-body"><div class="seq-lines"><i></i><i></i><i></i><i></i><i></i></div>%s</div></div>'
            '<div style="display:flex;gap:1.2vw;margin-top:1.6vh;align-items:center">'
            '<div class="chip warn"><i></i>%s</div>'
            '<div style="font-size:var(--fs-sm);color:var(--ink-2);line-height:1.45;flex:1">%s</div></div>'
            % (''.join(LANES), _seq(rows), left_chip, note))
    return slide(body, title, sub, 2)


